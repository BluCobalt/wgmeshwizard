//! Generation of `wg-quick` configuration files.

use std::collections::HashSet;
use std::fs;
use std::net::IpAddr;
use std::path::{Path, PathBuf};

use crate::crypto;
use crate::deploy;
use crate::model::{Connection, Host, Mesh, split_list};
use crate::timestamp;

/// Name of the `/etc/hosts`-compatible file written next to exported configs.
pub const HOSTS_FILE: &str = "hosts";

/// Render the complete configuration for one host.
pub fn generate_host_config(mesh: &Mesh, host_id: u64) -> Result<String, String> {
    let host = mesh
        .host(host_id)
        .ok_or_else(|| "host no longer exists".to_owned())?;

    if host.address.trim().is_empty() {
        return Err(format!("host {:?} has no address", host.name));
    }

    let public_key = crypto::public_key(&host.private_key)
        .map_err(|error| format!("host {:?}: {error}", host.name))?;
    let _ = public_key; // validate the private key before writing anything

    let defaults = &mesh.defaults;
    let mut output = String::new();

    output.push_str(&format!(
        "# Generated by wgmeshwizard for mesh {:?} at {}\n",
        defaults.name,
        timestamp::now_rfc3339()
    ));
    output.push_str("[Interface]\n");
    output.push_str(&format!("# Name: {}\n", host.name));
    output.push_str(&format!("Address = {}\n", host.address.trim()));
    output.push_str(&format!("PrivateKey = {}\n", host.private_key.trim()));
    output.push_str(&format!(
        "ListenPort = {}\n",
        host.effective_listen_port(defaults)
    ));

    let fwmark = host.effective_fwmark(defaults).trim();
    if !fwmark.is_empty() {
        output.push_str(&format!("FwMark = {fwmark}\n"));
    }
    let dns = host.effective_dns(defaults).trim();
    if !dns.is_empty() {
        output.push_str(&format!("DNS = {dns}\n"));
    }
    if let Some(mtu) = host.effective_mtu(defaults) {
        output.push_str(&format!("MTU = {mtu}\n"));
    }
    let table = host.effective_table(defaults).trim();
    if !table.is_empty() {
        output.push_str(&format!("Table = {table}\n"));
    }
    let pre_up = host.effective_pre_up(defaults).trim();
    if !pre_up.is_empty() {
        output.push_str(&format!("PreUp = {pre_up}\n"));
    }
    let post_up = host.effective_post_up(defaults).trim();
    if !post_up.is_empty() {
        output.push_str(&format!("PostUp = {post_up}\n"));
    }
    let pre_down = host.effective_pre_down(defaults).trim();
    if !pre_down.is_empty() {
        output.push_str(&format!("PreDown = {pre_down}\n"));
    }
    let post_down = host.effective_post_down(defaults).trim();
    if !post_down.is_empty() {
        output.push_str(&format!("PostDown = {post_down}\n"));
    }
    if host.effective_save_config(defaults) {
        output.push_str("SaveConfig = true\n");
    }

    let mut outgoing: Vec<&Connection> = mesh
        .connections
        .iter()
        .filter(|conn| conn.from == host_id && conn.enabled)
        .collect();
    outgoing.sort_by_key(|conn| {
        mesh.host(conn.to)
            .map(|host| host.name.to_ascii_lowercase())
            .unwrap_or_default()
    });

    for connection in outgoing {
        let Some(peer) = mesh.host(connection.to) else {
            continue;
        };

        let peer_public = crypto::public_key(&peer.private_key)
            .map_err(|error| format!("host {:?}: {error}", peer.name))?;

        output.push_str("\n[Peer]\n");
        output.push_str(&format!("# Name: {}\n", peer.name));
        output.push_str(&format!("PublicKey = {peer_public}\n"));

        if !connection.preshared_key.trim().is_empty() {
            crypto::decode_key(connection.preshared_key.trim(), "PresharedKey").map_err(
                |error| format!("connection {:?} -> {:?}: {error}", host.name, peer.name),
            )?;
            output.push_str(&format!(
                "PresharedKey = {}\n",
                connection.preshared_key.trim()
            ));
        }

        if let Some(endpoint) = mesh.resolved_endpoint(host_id, peer.id) {
            output.push_str(&format!("Endpoint = {endpoint}\n"));
        }

        let allowed_ips = peer_allowed_ips(mesh, peer);
        if allowed_ips.is_empty() {
            output.push_str(
                "# WARNING: this peer has no address and no AllowedIPs; add an address to use it.\n",
            );
        } else {
            output.push_str(&format!("AllowedIPs = {}\n", allowed_ips.join(", ")));
        }

        if let Some(keepalive) = host.effective_persistent_keepalive(defaults)
            && keepalive > 0
        {
            output.push_str(&format!("PersistentKeepalive = {keepalive}\n"));
        }
    }

    Ok(output)
}

fn peer_allowed_ips(mesh: &Mesh, peer: &Host) -> Vec<String> {
    let mut values = split_list(&peer.address);
    values.extend(split_list(peer.effective_allowed_ips(&mesh.defaults)));
    values
}

/// Render `/etc/hosts`-compatible records for every host address.
///
/// Each line has the form `address name [name.search-domain]`.  Hosts without
/// a parseable IP address are skipped, and a host with several addresses gets
/// one line per address.
pub fn generate_hosts_file(mesh: &Mesh) -> String {
    let domain = mesh.defaults.search_domain.trim().trim_matches('.');
    let mut output = String::new();
    output.push_str(&format!(
        "# Generated by wgmeshwizard for mesh {:?} at {}\n",
        mesh.defaults.name,
        timestamp::now_rfc3339()
    ));

    for host in &mesh.hosts {
        let name = hosts_name(&host.name, host.id);
        let mut seen = HashSet::new();
        for address in split_list(&host.address) {
            let Some(ip) = parse_host_ip(&address) else {
                continue;
            };
            if !seen.insert(ip) {
                continue;
            }

            if domain.is_empty() {
                output.push_str(&format!("{ip} {name}\n"));
            } else {
                output.push_str(&format!("{ip} {name} {name}.{domain}\n"));
            }
        }
    }

    output
}

fn parse_host_ip(address: &str) -> Option<IpAddr> {
    address.trim().split('/').next()?.trim().parse().ok()
}

fn hosts_name(name: &str, id: u64) -> String {
    let name = sanitize_filename(name);
    if name.is_empty() {
        format!("host-{id}")
    } else {
        name
    }
}

/// Write one `.conf` per host into `output_directory`.
///
/// Returns the paths that were written.  The whole project is validated before
/// anything is written, so a bad key or a missing address does not leave a
/// partially exported directory.
pub fn export_configs(mesh: &Mesh, output_directory: &Path) -> Result<Vec<PathBuf>, String> {
    let mut rendered = Vec::new();
    for host in &mesh.hosts {
        let config = generate_host_config(mesh, host.id)?;
        rendered.push((host, config));
    }

    fs::create_dir_all(output_directory)
        .map_err(|error| format!("could not create {}: {error}", output_directory.display()))?;

    let mut used_names = HashSet::new();
    let mut used_tunnels = HashSet::new();
    let mut deploy_hosts = Vec::new();
    let mut paths = Vec::new();
    for (host, config) in rendered {
        let mut stem = sanitize_filename(&host.name);
        if stem.is_empty() {
            stem = format!("host-{}", host.id);
        }
        let mut candidate = stem.clone();
        let mut suffix = 2;
        while !used_names.insert(candidate.clone()) {
            candidate = format!("{stem}-{suffix}");
            suffix += 1;
        }

        if mesh.defaults.enable_deployment {
            let tunnel = deploy::unique_tunnel_name(&candidate, &mut used_tunnels);
            let (target, port) = deploy::ssh_target_for(host, &mesh.defaults)
                .map(|(target, port)| (Some(target), port))
                .unwrap_or((None, None));
            deploy_hosts.push(deploy::HostScript {
                name: host.name.clone(),
                config: config.clone(),
                tunnel,
                target,
                port,
            });
        }

        let path = output_directory.join(format!("{candidate}.conf"));
        write_private(&path, config.as_bytes())?;
        paths.push(path);
    }

    let hosts_block = mesh
        .defaults
        .generate_hosts_file
        .then(|| generate_hosts_file(mesh));

    if let Some(hosts) = &hosts_block {
        let path = output_directory.join(HOSTS_FILE);
        fs::write(&path, hosts)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
    }

    if mesh.defaults.enable_deployment {
        let script =
            deploy::render_script(&mesh.defaults.name, &deploy_hosts, hosts_block.as_deref());
        deploy::write_script(&output_directory.join(deploy::SCRIPT_FILE), &script)?;
    }

    Ok(paths)
}

fn write_private(path: &Path, bytes: &[u8]) -> Result<(), String> {
    #[cfg(unix)]
    {
        use std::io::Write;
        use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};

        let mut file = fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o600)
            .open(path)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
        file.write_all(bytes)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
        fs::set_permissions(path, fs::Permissions::from_mode(0o600))
            .map_err(|error| format!("could not secure {}: {error}", path.display()))?;
    }

    #[cfg(not(unix))]
    {
        fs::write(path, bytes)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
    }

    Ok(())
}

pub fn sanitize_filename(name: &str) -> String {
    name.trim()
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.') {
                character
            } else {
                '_'
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Mesh;

    fn demo_mesh() -> (Mesh, u64, u64) {
        let mut mesh = Mesh::new();
        let a = mesh.add_host("alpha".into(), 0.0, 0.0);
        let b = mesh.add_host("bravo".into(), 100.0, 0.0);
        {
            let host = mesh.host_mut(a).unwrap();
            host.address = "10.100.0.1/32".into();
            host.private_key = crate::crypto::generate_private_key();
            host.endpoint = "203.0.113.10".into();
        }
        {
            let host = mesh.host_mut(b).unwrap();
            host.address = "10.100.0.2/32".into();
            host.private_key = crate::crypto::generate_private_key();
            host.endpoint = "203.0.113.20".into();
            host.listen_port = Some(51821);
        }
        (mesh, a, b)
    }

    #[test]
    fn config_includes_interface_and_peer() {
        let (mesh, a, _b) = demo_mesh();
        let config = generate_host_config(&mesh, a).unwrap();
        assert!(config.contains("Address = 10.100.0.1/32\n"));
        assert!(config.contains("ListenPort = 51820\n"));
        assert!(config.contains("Endpoint = 203.0.113.20:51821\n"));
        assert!(config.contains("AllowedIPs = 10.100.0.2/32\n"));
        assert!(config.contains("[Peer]\n"));
    }

    #[test]
    fn generated_headers_include_a_timestamp() {
        let (mesh, a, _) = demo_mesh();
        let config = generate_host_config(&mesh, a).unwrap();
        let header = config.lines().next().unwrap();
        assert!(header.starts_with("# Generated by wgmeshwizard for mesh \"my-mesh\" at "));
        assert!(header.ends_with('Z'));

        let hosts = generate_hosts_file(&mesh);
        let header = hosts.lines().next().unwrap();
        assert!(header.starts_with("# Generated by wgmeshwizard for mesh \"my-mesh\" at "));
        assert!(header.ends_with('Z'));
    }

    #[test]
    fn mesh_defaults_are_inherited() {
        let (mut mesh, a, _) = demo_mesh();
        mesh.defaults.dns = "1.1.1.1".into();
        mesh.defaults.mtu = Some(1380);
        mesh.defaults.pre_up = "echo before".into();
        let config = generate_host_config(&mesh, a).unwrap();
        assert!(config.contains("DNS = 1.1.1.1\n"));
        assert!(config.contains("MTU = 1380\n"));
        assert!(config.contains("PreUp = echo before\n"));
    }

    #[test]
    fn host_values_override_defaults() {
        let (mut mesh, a, _) = demo_mesh();
        mesh.defaults.dns = "1.1.1.1".into();
        mesh.defaults.mtu = Some(1380);
        {
            let host = mesh.host_mut(a).unwrap();
            host.dns = "9.9.9.9".into();
            host.mtu = Some(1280);
        }
        let config = generate_host_config(&mesh, a).unwrap();
        assert!(config.contains("DNS = 9.9.9.9\n"));
        assert!(!config.contains("DNS = 1.1.1.1\n"));
        assert!(config.contains("MTU = 1280\n"));
    }

    #[test]
    fn disabled_connection_is_omitted() {
        let (mut mesh, a, b) = demo_mesh();
        mesh.connection_mut(a, b).unwrap().enabled = false;
        let config = generate_host_config(&mesh, a).unwrap();
        assert!(!config.contains("[Peer]"));
    }

    #[test]
    fn invalid_preshared_key_is_rejected() {
        let (mut mesh, a, b) = demo_mesh();
        mesh.connection_mut(a, b).unwrap().preshared_key = "not-a-key".into();
        let error = generate_host_config(&mesh, a).unwrap_err();
        assert!(error.contains("PresharedKey"));
    }

    #[test]
    fn export_writes_one_file_per_host() {
        let (mesh, _, _) = demo_mesh();
        let dir = std::env::temp_dir().join(format!("wgmeshwizard-export-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let paths = export_configs(&mesh, &dir).unwrap();
        assert_eq!(paths.len(), 2);
        assert!(paths.iter().all(|path| path.exists()));
        assert!(!dir.join(crate::deploy::SCRIPT_FILE).exists());

        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            for path in &paths {
                assert_eq!(
                    fs::metadata(path).unwrap().permissions().mode() & 0o777,
                    0o600
                );
            }
        }

        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn hosts_file_uses_short_names_without_a_search_domain() {
        let (mesh, _, _) = demo_mesh();
        let hosts = generate_hosts_file(&mesh);
        assert!(hosts.contains("10.100.0.1 alpha\n"));
        assert!(hosts.contains("10.100.0.2 bravo\n"));
        assert!(!hosts.contains("alpha."));
    }

    #[test]
    fn hosts_file_appends_the_search_domain_and_every_address() {
        let (mut mesh, a, b) = demo_mesh();
        mesh.defaults.search_domain = ".example.tld.".into();
        {
            let host = mesh.host_mut(a).unwrap();
            host.name = "alpha primary".into();
            host.address = "10.100.0.1/32, fd00::1/128, not-an-ip".into();
        }
        {
            let host = mesh.host_mut(b).unwrap();
            host.address = "10.100.0.2/32".into();
        }

        let hosts = generate_hosts_file(&mesh);
        assert!(hosts.contains("10.100.0.1 alpha_primary alpha_primary.example.tld\n"));
        assert!(hosts.contains("fd00::1 alpha_primary alpha_primary.example.tld\n"));
        assert!(hosts.contains("10.100.0.2 bravo bravo.example.tld\n"));
        assert!(!hosts.contains("not-an-ip"));
    }

    #[test]
    fn export_writes_hosts_file_only_when_enabled() {
        let (mut mesh, _, _) = demo_mesh();
        mesh.defaults.search_domain = "example.tld".into();
        let dir = std::env::temp_dir().join(format!("wgmeshwizard-hosts-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);

        export_configs(&mesh, &dir).unwrap();
        assert!(!dir.join(HOSTS_FILE).exists());

        mesh.defaults.generate_hosts_file = true;
        export_configs(&mesh, &dir).unwrap();
        let hosts = fs::read_to_string(dir.join(HOSTS_FILE)).unwrap();
        assert!(hosts.contains("10.100.0.1 alpha alpha.example.tld\n"));
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn export_writes_static_deploy_script_when_enabled() {
        let (mut mesh, a, _) = demo_mesh();
        mesh.defaults.enable_deployment = true;
        mesh.defaults.generate_hosts_file = true;
        mesh.defaults.search_domain = "example.tld".into();
        mesh.defaults.ssh_user = "deploy".into();
        mesh.defaults.ssh_port = Some(2200);
        mesh.host_mut(a).unwrap().ssh_target = "root@10.0.0.5:2222".into();

        let dir = std::env::temp_dir().join(format!("wgmeshwizard-deploy-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        export_configs(&mesh, &dir).unwrap();

        let path = dir.join(crate::deploy::SCRIPT_FILE);
        let script = fs::read_to_string(&path).unwrap();
        assert!(script.starts_with("#!/bin/sh\n"));
        assert!(script.contains(
            "deploy_host 'alpha' 'root@10.0.0.5' '2222' 'alpha' <<'WGMESHWIZARD_CONFIG_0'"
        ));
        assert!(script.contains(
            "deploy_host 'bravo' 'deploy@203.0.113.20' '2200' 'bravo' <<'WGMESHWIZARD_CONFIG_1'"
        ));
        assert!(script.contains(crate::deploy::HOSTS_BEGIN_MARKER));
        assert!(script.contains(crate::deploy::HOSTS_END_MARKER));
        assert!(script.contains("HOSTS_AVAILABLE=1"));

        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            assert_eq!(
                fs::metadata(&path).unwrap().permissions().mode() & 0o777,
                0o700
            );
        }

        fs::remove_dir_all(&dir).unwrap();
    }
}
